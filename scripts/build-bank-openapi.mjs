#!/usr/bin/env node
/**
 * Generates an OpenAPI 3.1 document for the banking API from src/endpoints.ts,
 * the catalogue the docs page already renders and that check-catalogue.mjs
 * already diffs against the router. Generating it from that source means the
 * spec cannot drift from the documentation or the routes without the existing
 * guard failing.
 *
 * The banking API had no machine-readable contract at all: /openapi.yaml was
 * advertised on the developers page and in llms.txt, and served the homepage.
 *
 * Output: public/openapi.yaml (served as a static asset) and a JS module the
 * Worker can serve without a filesystem.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  BODYLESS_OPERATIONS,
  CREATED_OPERATIONS,
  SCHEMAS,
} from "../spec/banking/openapi/contracts.mjs";
import { REQUEST_BODIES } from "../spec/banking/openapi/request-contracts.mjs";
import {
  PAGINATED_RESPONSE_OPERATIONS,
  responseContractFor,
} from "../spec/banking/openapi/response-contracts.mjs";

const root = new URL("..", import.meta.url);
const ts = readFileSync(fileURLToPath(new URL("src/endpoints.ts", root)), "utf8");

/* The catalogue is a plain literal; read it without pulling in a TS toolchain. */
const families = [];
const familyRe = /name:\s*"([^"]+)",\s*blurb:\s*"([^"]*)"\s*,?\s*\n\s*endpoints:\s*\[([\s\S]*?)\n\s*\],/g;
const epRe = /\{\s*verb:\s*"([A-Z]+)",\s*path:\s*"([^"]+)",\s*does:\s*"((?:[^"\\]|\\.)*)",\s*access:\s*"([A-Z_]+)"\s*\}/g;

for (const [, name, blurb, body] of ts.matchAll(familyRe)) {
  const endpoints = [...body.matchAll(epRe)].map(([, verb, path, does, access]) => ({
    verb, path, does: does.replace(/\\"/g, '"'), access,
  }));
  families.push({ name, blurb, endpoints });
}

const total = families.reduce((n, f) => n + f.endpoints.length, 0);
if (total === 0) {
  console.error("build-bank-openapi: parsed 0 endpoints from src/endpoints.ts — refusing to write an empty spec");
  process.exit(1);
}

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const inline = (value) => JSON.stringify(value);
const opId = (verb, path) =>
  verb.toLowerCase() + path.replace(/^\/v2/, "").replace(/[:/]+([a-zA-Z])/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9]/g, "");

/* group by path so each path carries all its verbs */
const byPath = new Map();
for (const family of families) {
  for (const ep of family.endpoints) {
    const oaPath = ep.path.replace(/:([a-zA-Z_]+)/g, "{$1}");
    if (!byPath.has(oaPath)) byPath.set(oaPath, []);
    byPath.get(oaPath).push({ ...ep, family: family.name });
  }
}

const lines = [];
lines.push("# GENERATED by scripts/build-bank-openapi.mjs from src/endpoints.ts");
lines.push("# Do not edit by hand. Run `node scripts/build-bank-openapi.mjs`.");
lines.push("openapi: 3.1.0");
lines.push("info:");
lines.push('  title: "Blueballs banking API"');
lines.push('  version: "2026-08-06"');
lines.push(`  description: "${esc(`${total} endpoints across ${families.length} resource families. Money is always a decimal string with an explicit currency; errors are RFC 9457 problem+json. Self-serve a key with POST /v2/auth/signup.`)}"`);
lines.push("  license:");
lines.push('    name: "MIT"');
lines.push('    identifier: "MIT"');
lines.push("servers:");
lines.push('  - url: "https://blueballs.tech"');
lines.push('    description: "Public reference sandbox"');
lines.push("tags:");
for (const f of families) {
  lines.push(`  - name: "${esc(f.name)}"`);
  lines.push(`    description: "${esc(f.blurb)}"`);
}
lines.push("paths:");
const operationIds = new Set();
for (const [path, ops] of byPath) {
  lines.push(`  "${path}":`);
  const params = [...path.matchAll(/\{([a-zA-Z_]+)\}/g)].map((m) => m[1]);
  for (const op of ops) {
    const operationId = opId(op.verb, op.path);
    if (operationIds.has(operationId)) throw new Error(`Duplicate operationId: ${operationId}`);
    operationIds.add(operationId);
    lines.push(`    ${op.verb.toLowerCase()}:`);
    lines.push(`      summary: "${esc(op.does)}"`);
    lines.push(`      operationId: "${operationId}"`);
    lines.push(`      tags: ["${esc(op.family)}"]`);
    lines.push(`      x-blueballs-access: "${op.access}"`);
    if (op.access === "PUBLIC") lines.push("      security: []");
    if (op.access === "OPERATOR") lines.push("      security: [{ operatorKey: [] }]");
    if (params.length || PAGINATED_RESPONSE_OPERATIONS.has(operationId)) {
      lines.push("      parameters:");
      for (const p of params) {
        lines.push(`        - name: "${p}"`);
        lines.push("          in: path");
        lines.push("          required: true");
        lines.push("          schema: { type: string }");
      }
      if (PAGINATED_RESPONSE_OPERATIONS.has(operationId)) {
        lines.push('        - { name: "limit", in: query, required: false, schema: { type: integer, minimum: 1, maximum: 500, default: 100 } }');
        lines.push('        - { name: "cursor", in: query, required: false, schema: { type: string } }');
        lines.push('        - { name: "starting_after", in: query, required: false, schema: { type: string } }');
        lines.push('        - { name: "ending_before", in: query, required: false, schema: { type: string } }');
      }
    }
    if (!["GET", "DELETE"].includes(op.verb) && !BODYLESS_OPERATIONS.has(operationId)) {
      const request = REQUEST_BODIES[operationId];
      if (!request) throw new Error(`Missing request contract: ${operationId}`);
      lines.push("      requestBody:");
      lines.push(`        required: ${request.required}`);
      lines.push("        content:");
      lines.push("          application/json:");
      lines.push(`            schema: ${inline(request.schema)}`);
    }
    lines.push("      responses:");
    const successStatus = CREATED_OPERATIONS.has(operationId) ? "201" : "200";
    const response = responseContractFor({ operationId, verb: op.verb, family: op.family });
    lines.push(`        "${successStatus}":`);
    lines.push(`          description: "${esc(response.description)}"`);
    lines.push("          content:");
    lines.push("            application/json:");
    lines.push(`              schema: ${inline(response.schema)}`);
    lines.push(`              example: ${inline(response.example)}`);
    for (const [status, title] of [["400", "Invalid request"], ["401", "Missing or invalid API key"], ["403", "Insufficient access"], ["404", "Resource not found"], ["409", "State or idempotency conflict"], ["429", "Rate limit exceeded"]]) {
      if (op.access === "PUBLIC" && ["401", "403"].includes(status)) continue;
      lines.push(`        "${status}":`);
      lines.push(`          description: "${title}"`);
      lines.push("          content:");
      lines.push("            application/problem+json:");
      lines.push('              schema: { $ref: "#/components/schemas/Problem" }');
    }
    lines.push("        default:");
    lines.push('          description: "RFC 9457 problem document"');
    lines.push("          content:");
    lines.push("            application/problem+json:");
    lines.push('              schema: { $ref: "#/components/schemas/Problem" }');
  }
}
lines.push("components:");
lines.push("  securitySchemes:");
lines.push("    apiKey:");
lines.push("      type: apiKey");
lines.push("      in: header");
lines.push('      name: "x-api-key"');
lines.push("    operatorKey:");
lines.push("      type: apiKey");
lines.push("      in: header");
lines.push('      name: "x-fx-api-key"');
lines.push("  schemas:");
for (const [name, schema] of Object.entries(SCHEMAS)) {
  lines.push(`    ${name}: ${inline(schema)}`);
}
lines.push("security:");
lines.push("  - apiKey: []");

const yaml = lines.join("\n") + "\n";
if (operationIds.size !== total) throw new Error(`Expected ${total} unique operation IDs, got ${operationIds.size}`);
for (const operationId of BODYLESS_OPERATIONS) {
  if (!operationIds.has(operationId)) throw new Error(`Unknown bodyless operation: ${operationId}`);
}
for (const operationId of Object.keys(REQUEST_BODIES)) {
  if (!operationIds.has(operationId)) throw new Error(`Unknown request contract: ${operationId}`);
}
writeFileSync(fileURLToPath(new URL("public/openapi.yaml", root)), yaml);
writeFileSync(
  fileURLToPath(new URL("workers/site/openapi.generated.js", root)),
  `// GENERATED by scripts/build-bank-openapi.mjs. Do not edit.\nexport const BANK_OPENAPI_YAML = ${JSON.stringify(yaml)};\n`,
);
console.log(`wrote OpenAPI for ${total} endpoints across ${families.length} families (${byPath.size} paths)`);
