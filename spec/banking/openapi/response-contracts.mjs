function exampleFor(name) {
  return (
    EXAMPLES[name] ?? { id: `${name.toLowerCase()}_example`, status: "active" }
  );
}

export function responseContractFor({ operationId, verb, family }) {
  if (verb === "DELETE") {
    const example =
      operationId === "deleteKeys"
        ? { object: "list", data: [], revoked: 2 }
        : {
            id: "resource_example",
            object: family.toLowerCase().replaceAll(" ", "_"),
            deleted: true,
          };
    return {
      description: "Resource deletion or revocation result",
      schema: ref("DeleteResult"),
      example,
    };
  }
  const listSchema = LIST_SCHEMAS[operationId];
  if (listSchema) {
    return {
      description: `Paginated ${family.toLowerCase()} collection`,
      schema: {
        type: "object",
        additionalProperties: true,
        required: ["data"],
        properties: {
          object: { type: "string", const: "list" },
          data: { type: "array", items: ref(listSchema) },
          has_more: { type: "boolean" },
          next_cursor: { type: ["string", "null"] },
        },
      },
      example: {
        object: "list",
        data: [exampleFor(listSchema)],
        has_more: false,
        next_cursor: null,
      },
    };
  }
  const schemaName = SINGLE_SCHEMAS[operationId] ?? schemaForFamily(family);
  return {
    description: `${family} response`,
    schema: ref(schemaName),
    example: exampleFor(schemaName),
  };
}

